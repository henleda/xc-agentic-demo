#!/usr/bin/env python3
"""Render XC service-policy intent from the tool-access matrix and check agent configs against it.

Usage:
    python scripts/gen_policy.py                 # write deploy/xc/intent/service-policies.generated.yaml + check
    python scripts/gen_policy.py --check         # check only (CI / make check); non-zero exit on error
    python scripts/gen_policy.py --emit terraform  # TODO: emit volterra_service_policy HCL once schema verified

Exit codes: 0 ok, 1 consistency error, 2 bad input.

Findings:
    OVERDECLARED   agent config declares a tool the matrix does not grant (error unless demo_overdeclare: true)
    UNDECLARED     matrix grants a tool the agent config does not declare (warning)
    UNREGISTERED   agent config with no matrix entry (error unless unregistered: true)
    UNKNOWN_TOOL   tool not defined in matrix.tools (error)
    RL_DRIFT       matrix rate_limits disagree with the hand-written rl-tools / llm-lb intent (error)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MATRIX = ROOT / "config/policy/tool-access-matrix.yaml"
AGENTS_DIR = ROOT / "config/agents"
OUT = ROOT / "deploy/xc/intent/service-policies.generated.yaml"
SECURITY_INTENT = ROOT / "deploy/xc/intent/30-security.yaml"
LB_INTENT = ROOT / "deploy/xc/intent/20-load-balancers.yaml"

HEADER = (
    "# GENERATED by scripts/gen_policy.py from config/policy/tool-access-matrix.yaml. DO NOT EDIT.\n"
    "# Rule semantics: all matchers in a rule are ANDed; rules are evaluated in order; first match wins.\n"
    "# verify: R6 (multi-matcher AND incl. two JWT claims) — see docs/08-risks-and-verification.md\n"
)


class _NoAliasDumper(yaml.SafeDumper):
    def ignore_aliases(self, data):  # readable output: no &id001 / *id001 anchors
        return True


def load_yaml(p: Path):
    with p.open() as f:
        return yaml.safe_load(f)


def norm_tool_entry(entry) -> tuple[str, list[str] | None]:
    if isinstance(entry, str):
        return entry, None
    if isinstance(entry, dict) and "tool" in entry:
        return entry["tool"], entry.get("require_obo_roles")
    raise ValueError(f"bad tool entry: {entry!r}")


def build_tools_policy(m: dict) -> dict:
    rules = []
    servers = m["tool_servers"]
    for agent_id, a in m["agents"].items():
        role = a["agent_role"]
        users = a["allowed_user_roles"]
        touched_servers: list[str] = []
        for entry in a["tools"]:
            fq, obo = norm_tool_entry(entry)
            server, short = fq.split(".", 1)
            if server not in touched_servers:
                touched_servers.append(server)
            rules.append({
                "name": f"allow-{agent_id}-{server}-{short}".replace("_", "-"),
                "action": "allow",
                "match": {
                    "path_exact": servers[server]["path"],
                    "method": "POST",
                    "jwt_claims": {"agent_role": [role], "obo_role": list(obo or users)},
                    "headers": {"Mcp-Method": ["tools/call"], "Mcp-Name": [short]},
                },
            })
        for server in touched_servers:
            rules.append({
                "name": f"allow-{agent_id}-{server}-discovery",
                "action": "allow",
                "match": {
                    "path_exact": servers[server]["path"],
                    "method": "POST",
                    "jwt_claims": {"agent_role": [role], "obo_role": list(users)},
                    "headers": {"Mcp-Method": ["tools/list", "server/discover"]},
                },
            })
    rules.append({"name": "default-deny", "action": "deny", "match": "any"})
    return {"name": "sp-tools", "attached_to": ["tools-lb"], "rules": rules}


def build_llm_policy(m: dict) -> dict:
    rules = []
    for agent_id, a in m["agents"].items():
        for route in a.get("model_routes", []):
            rules.append({
                "name": f"allow-{agent_id}-route-{route}",
                "action": "allow",
                "match": {
                    # Only the model call. /v1/usage and other gateway endpoints stay unreachable for agents.
                    "path_exact": "/v1/converse",
                    "method": "POST",
                    "jwt_claims": {"agent_role": [a["agent_role"]], "obo_role": a["allowed_user_roles"]},
                    "headers": {"x-model-route": [route]},
                },
            })
    rules.append({"name": "default-deny", "action": "deny", "match": "any"})
    return {"name": "sp-llm", "attached_to": ["llm-lb"], "rules": rules}


def check_agents(m: dict, agents_dir: Path = AGENTS_DIR) -> tuple[list[str], list[str]]:
    errors, warnings = [], []
    known = set(m["tools"])
    for agent_id, a in m["agents"].items():
        for entry in a["tools"]:
            fq, _ = norm_tool_entry(entry)
            if fq not in known:
                errors.append(f"UNKNOWN_TOOL matrix agent={agent_id} tool={fq}")
            if fq.split(".", 1)[0] not in m["tool_servers"]:
                errors.append(f"UNKNOWN_SERVER matrix agent={agent_id} tool={fq}")
    for p in sorted(agents_dir.glob("*.yaml")):
        cfg = load_yaml(p)
        aid = cfg["agent_id"]
        declared = set(cfg.get("declared_tools", []))
        for t in declared - known:
            errors.append(f"UNKNOWN_TOOL {p.name} tool={t}")
        if aid not in m["agents"]:
            msg = f"UNREGISTERED {p.name} agent_id={aid} (no matrix entry; XC will deny everything it does)"
            (warnings if cfg.get("unregistered") else errors).append(msg)
            continue
        granted = {norm_tool_entry(e)[0] for e in m["agents"][aid]["tools"]}
        for t in sorted(declared - granted):
            msg = f"OVERDECLARED {p.name} tool={t} (agent will offer it to the model; XC will deny it)"
            (warnings if cfg.get("demo_overdeclare") else errors).append(msg)
        for t in sorted(granted - declared):
            warnings.append(f"UNDECLARED {p.name} tool={t} (granted but not offered to the model)")
        matrix_role = m["agents"][aid]["agent_role"]
        if cfg.get("agent_role") != matrix_role:
            errors.append(f"ROLE_MISMATCH {p.name} config={cfg.get('agent_role')} matrix={matrix_role}")
        if cfg.get("model_route") not in m["agents"][aid].get("model_routes", []):
            errors.append(f"ROUTE_NOT_GRANTED {p.name} route={cfg.get('model_route')}")
    return errors, warnings


def _same_limit(a: dict | None, b: dict | None) -> bool:
    return bool(a) and bool(b) and a.get("requests") == b.get("requests") and a.get("per") == b.get("per")


def check_rate_limits(m: dict, security: dict, lbs: dict) -> list[str]:
    """The matrix's rate_limits are the intent; rl-tools (30-security.yaml) and the llm-lb inline
    limit (20-load-balancers.yaml) are hand-written copies. Report any drift between them."""
    errors = []
    rl = m.get("rate_limits") or {}
    rl_tools = next((p for p in security.get("rate_limiter_policies", []) if p.get("name") == "rl-tools"), None)
    if rl_tools is None:
        return ["RL_DRIFT rl-tools policy missing from 30-security.yaml"]
    rules = rl_tools.get("rules", [])

    for o in rl.get("overrides", []):
        short = o["match"]["tool"].split(".", 1)[1]
        hit = next((r for r in rules if isinstance(r.get("match"), dict)
                    and r["match"].get("header", {}).get("Mcp-Name") == short), None)
        if hit is None:
            errors.append(f"RL_DRIFT rl-tools has no rule for Mcp-Name={short} (matrix override {o['match']['tool']})")
        elif not _same_limit(hit.get("limit"), o.get("limit")):
            errors.append(f"RL_DRIFT rl-tools Mcp-Name={short} limit={hit.get('limit')} matrix={o.get('limit')}")

    default = next((r for r in rules if r.get("match") == "any"), None)
    want = rl.get("tools_default_per_agent_identity")
    if want and (default is None or not _same_limit(default.get("limit"), want)):
        errors.append(f"RL_DRIFT rl-tools default={default and default.get('limit')} matrix={want}")

    llm_lb = next((lb for lb in lbs.get("http_load_balancers", []) if lb.get("name") == "llm-lb"), None)
    want = rl.get("llm_default_per_agent_identity")
    if want and (llm_lb is None or not _same_limit(llm_lb.get("rate_limit"), want)):
        errors.append(f"RL_DRIFT llm-lb rate_limit={llm_lb and llm_lb.get('rate_limit')} matrix={want}")
    return errors


def main(argv: list[str] | None = None, out: Path = OUT) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="check only; do not write")
    ap.add_argument("--emit", choices=["intent", "terraform"], default="intent")
    args = ap.parse_args(argv)

    try:
        m = load_yaml(MATRIX)
        security = load_yaml(SECURITY_INTENT)
        lbs = load_yaml(LB_INTENT)
    except Exception as e:  # noqa: BLE001
        print(f"cannot read matrix or intent: {e}", file=sys.stderr)
        return 2

    errors, warnings = check_agents(m)
    errors += check_rate_limits(m, security, lbs)
    for w in warnings:
        print(f"WARN  {w}")
    for e in errors:
        print(f"ERROR {e}")

    if args.emit == "terraform":
        print("TODO: emit volterra_service_policy HCL after verifying the provider schema (CLAUDE.md rule 2)",
              file=sys.stderr)
        return 2

    doc = {"service_policies": [build_tools_policy(m), build_llm_policy(m)]}
    rendered = HEADER + yaml.dump(doc, Dumper=_NoAliasDumper, sort_keys=False, width=120)
    if args.check:
        if out.exists() and out.read_text() != rendered:
            print(f"ERROR STALE {out.name} is out of date; run scripts/gen_policy.py")
            errors.append("stale")
    else:
        out.write_text(rendered)
        n = sum(len(p["rules"]) for p in doc["service_policies"])
        print(f"wrote {out.name} ({n} rules)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
