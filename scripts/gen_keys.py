#!/usr/bin/env python3
"""Create the IdP signing key, every client secret and the AI gateway key, and publish the public JWKS.

Usage:
    uv run python scripts/gen_keys.py               # create anything missing; never overwrites
    uv run python scripts/gen_keys.py --if-missing  # same; quiet when everything already exists (make local-up)
    uv run python scripts/gen_keys.py --rotate      # replace the key and every secret (all tokens become invalid)
    uv run python scripts/gen_keys.py --root PATH   # work on another checkout (tests use a tmp dir)

Writes (see scripts/README.md):
    .secrets/idp-signing-key.pem    RSA 2048 private key, PKCS#8 PEM
    .secrets/secrets.env            NAME=value per client secret, GATEWAY_API_KEY and CLIENT_SECRETS_JSON
    deploy/xc/generated/jwks.json   the public JWKS, always rewritten from the current key

.secrets/ is mode 0700 and its files 0600. Secret names come from config/personas.yaml clients of kind agent,
service and partner, so a new client gets a secret automatically. A secret whose client is no longer in
personas.yaml is kept (with a warning naming it) so putting the client back restores the same value; only
--rotate drops it. If .env sets GRANITE_SUPPLY_SECRET or GATEWAY_API_KEY, that value is used (and kept in sync)
so the cockpit and the vK8s Secret always agree. Nothing secret is ever printed.

Exit codes: 0 ok, 2 bad input (missing personas.yaml or no secret-bearing client in it, unreadable key, a value
that cannot go in an env file). On exit 2 nothing is written.
"""

from __future__ import annotations

import argparse
import json
import os
import secrets
import sys
from pathlib import Path

import yaml
from copperline_common.credentials import secret_env_name
from copperline_common.jwt import load_private_key, public_jwks
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from envfile import format_env_file, read_env_file

ROOT = Path(__file__).resolve().parent.parent
SECRETS_DIR = ".secrets"
KEY_FILE = "idp-signing-key.pem"
SECRETS_FILE = "secrets.env"
JWKS_FILE = Path("deploy/xc/generated/jwks.json")
PERSONAS_FILE = Path("config/personas.yaml")

SECRET_CLIENT_KINDS = ("agent", "service", "partner")
GATEWAY_KEY_NAME = "GATEWAY_API_KEY"
ALL_SECRETS_NAME = "CLIENT_SECRETS_JSON"
ENV_OVERRIDES = ("GRANITE_SUPPLY_SECRET", GATEWAY_KEY_NAME)  # .env wins for these

SECRETS_HEADER = """Generated by scripts/gen_keys.py. DO NOT COMMIT. Regenerate with --rotate.
CLIENT_SECRETS_JSON repeats the client secrets above as one JSON object (client_id -> secret) for the idp."""


class GenKeysError(Exception):
    """Bad input; the message says what to fix. Never contains a secret."""


# ---- inputs -------------------------------------------------------------------------------------------------------


def secret_clients(root: Path) -> list[str]:
    """client_ids of every personas.yaml client that needs a secret, in file order.

    An empty list is refused: it means a typo (say `clientz:`) or a truncated file, not "no clients"."""
    path = root / PERSONAS_FILE
    if not path.is_file():
        raise GenKeysError(f"{PERSONAS_FILE} not found under {root}")
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    clients = [c["client_id"] for c in data.get("clients") or [] if c.get("kind") in SECRET_CLIENT_KINDS]
    if not clients:
        kinds = ", ".join(SECRET_CLIENT_KINDS)
        raise GenKeysError(f"{PERSONAS_FILE} has no clients of kind {kinds}; check its 'clients:' list")
    return clients


def new_secret() -> str:
    return secrets.token_urlsafe(32)


# ---- the signing key ----------------------------------------------------------------------------------------------


def new_private_key_pem() -> bytes:
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    return key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()
    )


def ensure_signing_key(key_path: Path, rotate: bool) -> tuple[rsa.RSAPrivateKey, bool]:
    """(private key, changed). Loads the existing key unless rotating or there is none."""
    if key_path.is_file() and not rotate:
        try:
            return load_private_key(key_path.read_bytes()), False
        except ValueError as e:
            raise GenKeysError(f"{key_path} is not a usable RSA private key ({e}); fix it or use --rotate") from None
    pem = new_private_key_pem()
    write_private(key_path, pem.decode("ascii"))
    return load_private_key(pem), True


# ---- the secrets --------------------------------------------------------------------------------------------------


def wanted_names(clients: list[str]) -> list[str]:
    """Every secret name personas.yaml calls for, in output order."""
    return [secret_env_name(client_id) for client_id in clients] + [GATEWAY_KEY_NAME]


def unused_names(clients: list[str], existing: dict[str, str]) -> list[str]:
    """Names in secrets.env that no personas.yaml client uses any more (a removed client, or a typo in its id)."""
    wanted = wanted_names(clients)
    return [name for name, value in existing.items() if value and name not in wanted and name != ALL_SECRETS_NAME]


def plan_secrets(
    clients: list[str], existing: dict[str, str], dotenv: dict[str, str], rotate: bool
) -> tuple[dict[str, str], list[str]]:
    """(name -> value for every secret in output order, names whose value is new or changed).

    Without --rotate, unused names are carried forward unchanged after the wanted ones, so a client that is
    removed from personas.yaml and later put back keeps its secret. --rotate drops them."""
    values: dict[str, str] = {}
    changed: list[str] = []
    for name in wanted_names(clients):
        if name in ENV_OVERRIDES and dotenv.get(name):
            value = dotenv[name]
        elif existing.get(name) and not rotate:
            value = existing[name]
        else:
            value = new_secret()
        values[name] = value
        if existing.get(name) != value:
            changed.append(name)
    if not rotate:
        for name in unused_names(clients, existing):
            values[name] = existing[name]
    return values, changed


def client_secrets_json(clients: list[str], values: dict[str, str]) -> str:
    """Compact JSON (no spaces) so the env-file line needs no quoting."""
    mapping = {client_id: values[secret_env_name(client_id)] for client_id in clients}
    return json.dumps(mapping, separators=(",", ":"))


# ---- files --------------------------------------------------------------------------------------------------------


def ensure_private_dir(path: Path) -> None:
    path.mkdir(mode=0o700, parents=True, exist_ok=True)
    os.chmod(path, 0o700)


def write_private(path: Path, text: str) -> None:
    """Write a 0600 file. It is created 0600, so the content is never readable by others, even briefly."""
    temp = path.with_name(path.name + ".tmp")
    temp.unlink(missing_ok=True)
    fd = os.open(temp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.chmod(temp, 0o600)
    os.replace(temp, path)


def write_if_changed(path: Path, text: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def secure_existing(paths: list[Path]) -> None:
    """Repair modes on files an earlier run (or a hand edit) left too open."""
    for path in paths:
        if path.is_file():
            os.chmod(path, 0o600)


# ---- main ---------------------------------------------------------------------------------------------------------


def unused_warning(unused: list[str], rotate: bool) -> str:
    """Names only, never values."""
    names = ", ".join(unused)
    if rotate:
        return f"dropped {names} from {SECRETS_DIR}/{SECRETS_FILE}: no client in {PERSONAS_FILE} needs them"
    return (
        f"kept {names} in {SECRETS_DIR}/{SECRETS_FILE} although no client in {PERSONAS_FILE} needs them; "
        "put the client back to reuse the value, or run --rotate to drop them"
    )


def generate(root: Path, *, rotate: bool = False) -> tuple[list[str], list[str]]:
    """Create or rotate everything. Returns (one human-readable line per thing that changed, warnings); no values.

    Bad input is found before anything is written, so a failed --rotate never leaves a new key next to old
    secrets and an old jwks.json."""
    clients = secret_clients(root)
    secrets_dir = root / SECRETS_DIR
    key_path, env_path = secrets_dir / KEY_FILE, secrets_dir / SECRETS_FILE

    existing = read_env_file(env_path)
    unused = unused_names(clients, existing)
    values, changed = plan_secrets(clients, existing, read_env_file(root / ".env"), rotate)
    values[ALL_SECRETS_NAME] = client_secrets_json(clients, values)
    try:
        text = format_env_file(values, SECRETS_HEADER)
    except ValueError as e:
        raise GenKeysError(f"{e} (check .env and {SECRETS_DIR}/{SECRETS_FILE})") from None
    warnings = [unused_warning(unused, rotate)] if unused else []

    ensure_private_dir(secrets_dir)
    secure_existing([key_path, env_path])
    report: list[str] = []
    private_key, key_changed = ensure_signing_key(key_path, rotate)
    if key_changed:
        report.append(f"{'rotated' if rotate else 'created'} {SECRETS_DIR}/{KEY_FILE}")

    if not env_path.is_file() or env_path.read_text(encoding="utf-8") != text:
        write_private(env_path, text)
        report.append(f"wrote {SECRETS_DIR}/{SECRETS_FILE}" + (f" (new: {', '.join(changed)})" if changed else ""))

    jwks_text = json.dumps(public_jwks(private_key), indent=2) + "\n"
    if write_if_changed(root / JWKS_FILE, jwks_text):
        report.append(f"wrote {JWKS_FILE}")
    return report, warnings


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--if-missing", action="store_true", help="create anything missing; quiet if nothing is")
    mode.add_argument("--rotate", action="store_true", help="replace the key and every secret")
    parser.add_argument("--root", type=Path, default=ROOT, help="repo root to work in (default: this checkout)")
    args = parser.parse_args(argv)

    try:
        report, warnings = generate(args.root.resolve(), rotate=args.rotate)
    except GenKeysError as e:
        print(f"gen_keys: {e}", file=sys.stderr)
        return 2
    for warning in warnings:
        print(f"gen_keys: warning: {warning}", file=sys.stderr)
    for line in report:
        print(f"gen_keys: {line}")
    if not report and not args.if_missing:
        print("gen_keys: everything already exists; nothing changed (use --rotate to replace)")
    if args.rotate:
        print("gen_keys: every issued token is now invalid; re-run render_secrets.py and redeploy the idp")
    return 0


if __name__ == "__main__":
    sys.exit(main())
