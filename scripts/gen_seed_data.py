def sql_value(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, (int, Decimal)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def insert(table: str, row: tuple) -> str:
    return f"INSERT INTO {table} VALUES ({', '.join(sql_value(v) for v in row)});\n"


def render_seed_sql(data: SeedData) -> str:
    parts = [
        f"-- {GENERATED}\n",
        "-- erp-mock rebuilds a fresh SQLite database from this file at startup and on POST /admin/reset.\n",
        "-- Card numbers are published TEST numbers only.\n",
        "BEGIN TRANSACTION;\n",
        SCHEMA,
    ]
    parts += [insert("stores", row) for row in data.stores]
    parts += [insert("products", (p.sku, p.name, p.category, p.price)) for p in data.products]
    parts += [insert("customers", row) for row in data.customers]
    for o in data.orders:
        parts.append(insert("orders", (o.order_id, o.customer_id, o.status, o.placed_at, o.eta, o.total,
                                       o.card_brand, o.card_number, o.card_exp)))
    for o in data.orders:
        parts += [insert("order_items", (o.order_id, i.sku, i.qty, i.unit_price)) for i in o.items]
    parts += [insert("inventory", row) for row in data.inventory]
    parts.append("COMMIT;\n")
    return "".join(parts)


def render_catalog_json(data: SeedData) -> str:
    products = [
        {
            "sku": p.sku,
            "name": p.name,
            "category": p.category,
            "price": float(p.price),
            "description": p.description,
            "reviews": data.reviews[p.sku],
        }
        for p in data.products
    ]
    doc = {"_generated": GENERATED, "products": products}
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render(root: Path) -> dict[Path, bytes]:
    """{relative path: exact file bytes} for both outputs."""
    path = root / POISONED_REVIEW
    try:
        poisoned_review = path.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as e:
        raise SeedError(f"cannot read {POISONED_REVIEW}: {e}") from None
    data = build(poisoned_review)
    return {
        SEED_SQL: render_seed_sql(data).encode("utf-8"),
        CATALOG_JSON: render_catalog_json(data).encode("utf-8"),
    }


