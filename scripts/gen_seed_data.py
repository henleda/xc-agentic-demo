def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a committed file is stale; write nothing")
    ap.add_argument("--root", type=Path, default=ROOT, help="repo root to read from and write to")
    args = ap.parse_args(argv)

    try:
        outputs = render(args.root)
    except SeedError as e:
        print(f"ERROR {e}", file=sys.stderr)
        return 2

    if args.check:
        stale = [rel for rel, content in outputs.items() if read_or_none(args.root / rel) != content]
        for rel in stale:
            print(f"ERROR STALE {rel} is out of date; run: uv run python scripts/gen_seed_data.py")
        return 1 if stale else 0

    for rel, content in outputs.items():
        target = args.root / rel
        if read_or_none(target) == content:
            print(f"unchanged {rel}")
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
        print(f"wrote {rel}")
    return 0


def read_or_none(path: Path) -> bytes | None:
    try:
        return path.read_bytes()
    except FileNotFoundError:
        return None


if __name__ == "__main__":
    sys.exit(main())
