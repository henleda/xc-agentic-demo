#!/usr/bin/env python3
"""Generate the ERP seed (seed.sql) and the public catalog (catalog.json) from ONE product list.

Usage:
    uv run python scripts/gen_seed_data.py               # write both files
    uv run python scripts/gen_seed_data.py --check       # exit 1 if either committed file is stale; writes nothing
    uv run python scripts/gen_seed_data.py --root PATH   # work on another checkout (tests use a tmp dir)

Writes (both committed, so data changes show up in diffs):
    services/erp-mock/erp_mock/seed.sql      schema + rows; erp-mock rebuilds its SQLite DB from it at start and reset
    services/mcp-servers/data/catalog.json   the same 60 products, with descriptions and reviews (mcp-catalog)

Reads:
    scenarios/data/poisoned-review.txt       TNT-ALPINE-2 review index 2, copied byte for byte (scenario S1)

The hero rows the scenarios depend on (services/erp-mock/README.md) are written out literally below. Everything
else comes from random.Random seeded with fixed strings, one per section, so editing one section never reshuffles
another. Money is Decimal, files are written as UTF-8 bytes with "\\n" newlines, JSON keys are sorted and nothing
depends on the clock: the output is byte-identical on every run and platform.

Exit codes: 0 ok (or up to date), 1 stale (--check), 2 bad input.
"""

