"""erp-mock settings, read once from env at startup. Tests build a Settings directly."""

import os
from dataclasses import dataclass, field
from pathlib import Path

from copperline_common.jwt import JwksVerifier

DEFAULT_DB_PATH = "/tmp/erp.sqlite3"  # /tmp is the writable emptyDir; the image root is read-only
DEFAULT_ISSUER = "https://idp.copperline.demo"
DEFAULT_PORT = 8081
DEFAULT_ADMIN_PORT = 8181
SEED_SQL = Path(__file__).resolve().parent / "seed.sql"  # generated by scripts/gen_seed_data.py


@dataclass
class Settings:
    db_path: Path
    issuer: str
    jwks_path: str | None = None  # a JWKS file (EC2: the host cannot resolve vK8s names) ...
    idp_base_url: str | None = None  # ... or else ${IDP_BASE_URL}/.well-known/jwks.json
    port: int = DEFAULT_PORT
    admin_port: int = DEFAULT_ADMIN_PORT
    host: str = "0.0.0.0"  # both apps; tests bind 127.0.0.1
    seed_path: Path = field(default=SEED_SQL)

    @classmethod
    def from_env(cls) -> "Settings":
        """Raises RuntimeError on a value erp-mock cannot start with."""
        settings = cls(
            db_path=Path(os.environ.get("ERP_DB_PATH") or DEFAULT_DB_PATH),
            issuer=os.environ.get("ISSUER") or DEFAULT_ISSUER,
            jwks_path=os.environ.get("JWKS_PATH") or None,
            idp_base_url=os.environ.get("IDP_BASE_URL") or None,
            port=port_from_env("ERP_PORT", DEFAULT_PORT),
            admin_port=port_from_env("ERP_ADMIN_PORT", DEFAULT_ADMIN_PORT),
        )
        settings.jwks_source()  # fail at startup, not on the first request
        return settings

    def jwks_source(self) -> str:
        """Where the token-signing keys come from: the file, else the IdP URL."""
        if self.jwks_path:
            return self.jwks_path
        if self.idp_base_url:
            return f"{self.idp_base_url.rstrip('/')}/.well-known/jwks.json"
        raise RuntimeError("no token keys: set JWKS_PATH (a JWKS file) or IDP_BASE_URL")

    def verifier(self) -> JwksVerifier:
        if self.jwks_path:
            return JwksVerifier(jwks_path=self.jwks_path, issuer=self.issuer)
        return JwksVerifier(jwks_url=self.jwks_source(), issuer=self.issuer)


def port_from_env(name: str, default: int) -> int:
    raw = os.environ.get(name, "").strip()
    if not raw:
        return default
    if not raw.isdigit() or not 0 < int(raw) < 65536:
        raise RuntimeError(f"{name} must be a TCP port number, got {raw!r}")
    return int(raw)
